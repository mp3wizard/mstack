#!/usr/bin/env python3
"""Regenerate docs/sources.md from docs/research/findings.json."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "docs/research/findings.json").read_text())
TITLES = {
    "sdlc-process": "Design process frameworks in the SDLC",
    "laws-heuristics": "UX laws, heuristics, and design principles",
    "accessibility-inclusive": "Accessibility and inclusive design",
    "design-systems-handoff": "Design systems, platform guidelines, handoff, and design QA",
    "research-validation": "User research, validation, and UX metrics",
    "agent-skill-handbooks": "Agent skills that already encode design knowledge",
    "community-x": "Community signal (X posts verified through the syndication API)",
    "critic-gapfill": "Gap fill: ethics, content design, IA, AI features, motion, data viz, i18n, maturity",
}


def cell(s):
    return " ".join(str(s or "").split()).replace("|", "\\|")


out = [
    "# Sources",
    "",
    "Generated by `scripts/gen-sources.py` from `docs/research/findings.json` (research run of 2026-10-15). "
    "Do not edit by hand.",
    "",
    "The license column is what the research recorded from each publisher's license or terms page. "
    "How a skill may use each source (adapt, quote with notice, or link and paraphrase) follows the tiers in "
    "[handbook-map.md](handbook-map.md#layer-2-handbooks-as-the-source-of-truth).",
    "",
]
seen = set()
for angle in data["angles"] + [data["critic"]]:
    out += [f"## {TITLES.get(angle['angle'], angle['angle'])}", "", "| Source | Publisher | Version or date | License |", "|---|---|---|---|"]
    for s in angle["sources"]:
        key = s["url"]
        dup = " (also listed above)" if key in seen else ""
        seen.add(key)
        out.append(f"| [{cell(s['name'])}]({s['url']}){dup} | {cell(s.get('publisher'))} | {cell(s.get('version_or_date'))[:160]} | {cell(s['license'])[:200]} |")
    out.append("")
(ROOT / "docs/sources.md").write_text("\n".join(out))
print(f"wrote docs/sources.md with {len(seen)} unique sources")
